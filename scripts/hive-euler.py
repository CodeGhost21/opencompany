class _StatementExtractor(HTMLParser):
    """Strip `minimal=<N>`'s HTML down to text, keeping paragraph breaks.

    `$...$` LaTeX is never touched — it is not a tag, so it simply passes
    through `handle_data` unchanged, dollar signs and all.
    """

    BREAK = "\x00"

    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.parts: list[str] = []

    def handle_starttag(self, tag: str, attrs) -> None:  # noqa: ANN001
        if tag in _BLOCK_TAGS:
            self.parts.append(self.BREAK)

    def handle_endtag(self, tag: str) -> None:
        if tag in _BLOCK_TAGS:
            self.parts.append(self.BREAK)

    def handle_data(self, data: str) -> None:
        self.parts.append(data)

    def handle_entityref(self, name: str) -> None:
        self.parts.append(html.unescape(f"&{name};"))

    def handle_charref(self, name: str) -> None:
        self.parts.append(html.unescape(f"&#{name};"))


def clean_statement_html(raw: str) -> str:
    """Tags out, entities unescaped, `$...$` kept as-is, blank runs collapsed."""
    extractor = _StatementExtractor()
    extractor.feed(raw)
    paragraphs = []
    for chunk in "".join(extractor.parts).split(_StatementExtractor.BREAK):
        collapsed = re.sub(r"\s+", " ", chunk).strip()
        if collapsed:
            paragraphs.append(collapsed)
    return "\n\n".join(paragraphs)


def fetch_statement(pid: str, cache_dir: Path, do_fetch: bool, log) -> str | None:
    """The problem statement for `pid`, from the cache or the network.

    A hit under `cache_dir` is trusted forever — a published statement does
    not change — so a second run of the same ladder makes zero requests.
    """
    cache_file = cache_dir / f"{pid}.txt"
    if cache_file.exists():
        return cache_file.read_text(encoding="utf-8")
    if not do_fetch:
        return None
    url = FETCH_URL.format(n=pid)
    req = urllib.request.Request(url, headers={"User-Agent": "hive-euler/1.0"})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310
            raw = resp.read().decode("utf-8", errors="replace")
    except (urllib.error.URLError, OSError, TimeoutError) as err:
        log(f"!! fetch failed for problem {pid}: {err}")
        return None
    text = clean_statement_html(raw)
    if not text:
        return None
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_file.write_text(text, encoding="utf-8")
    return text


_ANSWER_LINE = re.compile(r"^\s*(\d+)\.\s+(\S+)\s*$")


def load_answers(path: str | None) -> dict[str, str]:
    """Published answers from a `Solutions.md`-shaped file: `123. 456789` lines."""
    if not path:
        return {}
    answers: dict[str, str] = {}
    try:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                m = _ANSWER_LINE.match(line)
                if m:
                    answers[m.group(1)] = m.group(2)
    except OSError as err:
        raise SystemExit(f"--answers {path}: {err}") from None
    return answers


def resolve_problem(
    pid: str, answers: dict[str, str], cache_dir: Path, do_fetch: bool, log
) -> dict[str, str] | None:
    """A problem's title/statement/answer, offline table first, fetch to fill gaps."""
    known = PROBLEMS.get(pid)
    statement = (known or {}).get("statement")
    if do_fetch or statement is None:
        fetched = fetch_statement(pid, cache_dir, do_fetch, log)
        if fetched:
            statement = fetched
    if statement is None:
        log(f"!! no statement for problem {pid} (not fetched, not in the offline table)")
        return None
    answer = answers.get(pid) or (known or {}).get("answer")
    if answer is None:
        log(f"!! no published answer known for problem {pid}; will not be able to grade it")
    title = (known or {}).get("title", f"Problem {pid}")
    return {"title": title, "statement": statement, "answer": answer}


def parse_problem_spec(spec: str) -> list[str]:
    """`"200-210,233,301"` -> ordered, de-duplicated problem ids."""
    seen: set[str] = set()
    ids: list[str] = []
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        if "-" in chunk:
            lo_s, _, hi_s = chunk.partition("-")
            lo, hi = int(lo_s), int(hi_s)
            if hi < lo:
                lo, hi = hi, lo
            span = (str(n) for n in range(lo, hi + 1))
        else:
            span = (chunk,)
        for pid in span:
            if pid not in seen:
                seen.add(pid)
                ids.append(pid)
    return ids


def analyze_transcript(turns: list[dict], report_text: str | None) -> dict:
    """Count moves, speakers, mentions and citations; check who backed the winner.

    `carried_supporters_other_than_proposer` is the direct check on the
    failure a live run showed: a room can converge on a proposal with two
    `!propose`s and nobody's `!support` behind either. `None` when the report
    named no topic (deadlocked/exhausted/idle) or nobody ever proposed it.
    """
    moves = {kind: 0 for kind in MOVE_KINDS}
    speakers: set[str] = set()
    mentions = 0
    citations = 0
    proposer_of: dict[str, str] = {}
    supporters_of: dict[str, set[str]] = {}

    for turn in turns:
        text = (turn.get("text") or "").strip()
        author = turn.get("author")
        if author:
            speakers.add(author)
        if not text:
            continue
        mentions += len(_MENTION_RE.findall(text))
        citations += len(set(_CITE_RE.findall(text)))
        first_line = text.splitlines()[0]
        match = _MARKER_RE.match(first_line)
        if not match:
            continue
        kind = match.group(1)
        bucket = "pin" if kind == "unpin" else kind
        if bucket in moves:
            moves[bucket] += 1
        topic_match = _TOPIC_RE.search(first_line)
        topic = topic_match.group(1) if topic_match else None
        if not (topic and author):
            continue
        if kind == "propose":
            proposer_of.setdefault(topic, author)
        elif kind in ("support", "commit"):
            supporters_of.setdefault(topic, set()).add(author)

    carried_topic = None
    if report_text:
        m = re.search(r"#(\S+)", report_text)
        if m:
            carried_topic = m.group(1).rstrip(".,;:")

    diverse_support = None
    if carried_topic is not None:
        proposer = proposer_of.get(carried_topic)
        backers = supporters_of.get(carried_topic, set())
        diverse_support = any(a != proposer for a in backers)

    return {
        "moves": moves,
        "distinct_speakers": len(speakers),
        "mentions": mentions,
        "citations": citations,
        "carried_topic": carried_topic,
        "carried_supporters_other_than_proposer": diverse_support,
    }


class Host:
    """A cookie-carrying HTTP client for one OpenCompany host."""

    def __init__(self, base: str) -> None:
        self.base = base.rstrip("/")
        self.jar = http.cookiejar.CookieJar()
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(self.jar))

    def call(self, method: str, path: str, body: dict | None = None, timeout: float = 120):
        data = None if body is None else json.dumps(body).encode()
        req = urllib.request.Request(self.base + path, data=data, method=method)
        req.add_header("accept", "application/json")
        if data is not None:
            req.add_header("content-type", "application/json")
        try:
            with self.opener.open(req, timeout=timeout) as resp:
                raw = resp.read()
                return resp.status, (json.loads(raw) if raw else None)
        except urllib.error.HTTPError as err:
            raw = err.read()
            try:
                return err.code, json.loads(raw)
            except ValueError:
                return err.code, raw.decode(errors="replace")

    def sign_in(self) -> None:
        """No-op when auth is `none`; otherwise the loopback dev-code flow."""
        status, _ = self.call("GET", f"{SCOPE}/chat/history?limit=1")
        if status == 200:
            return
        status, body = self.call("POST", f"{SCOPE}/auth/request", {"email": ADMIN_EMAIL})
        code = (body or {}).get("dev_code") if isinstance(body, dict) else None
        if not code:
            raise SystemExit(f"sign-in: no dev_code from auth/request ({status}: {body})")
        status, body = self.call("POST", f"{SCOPE}/auth/verify", {"code": code})
        if status >= 300:
            raise SystemExit(f"sign-in: verify refused ({status}: {body})")

    # -- the operator's two jobs: stating the problem and answering approvals --

    def say(self, desk: str, text: str) -> None:
        status, body = self.call("POST", f"{SCOPE}/chat", {"text": text, "chat": desk}, timeout=3600)
        if status >= 300:
            raise RuntimeError(f"chat POST failed ({status}): {body}")

    def approve_all(self) -> list[str]:
        status, body = self.call("GET", f"{SCOPE}/approvals")
        if status != 200 or not isinstance(body, list):
            return []
        approved = []
        for approval in body:
            aid = approval.get("id")
            status, _ = self.call(
                "POST", f"{SCOPE}/approvals/{aid}", {"verdict": "approve", "detach": True}
            )
            if status < 300:
                approved.append(approval.get("kind", "?"))
        return approved

    def history(self, desk: str, limit: int = 200) -> list[dict]:
        query = urllib.parse.urlencode({"desk": desk, "limit": limit})
        status, body = self.call("GET", f"{SCOPE}/chat/history?{query}")
        if status != 200 or not isinstance(body, list):
            return []
        return body


INT = re.compile(r"\d{1,3}(?:,\d{3})+|\d+")


def integers_in(text: str) -> list[str]:
    return [t.replace(",", "") for t in INT.findall(text)]


def wait_for_report(
    host: Host, desk: str, after_id: int, timeout: float, log, poster=None, failure=None
) -> tuple[dict | None, list[dict]]:
    """Poll the desk until a hive-report bubble newer than `after_id` lands."""
    deadline = time.time() + timeout
    seen: set[str] = set()
    approved_total: list[str] = []
    while time.time() < deadline:
        if failure:
            log(f"    !! chat POST failed: {failure[0]}")
            return None, [m for m in host.history(desk) if int(m.get("id", "0")) > after_id]
        approved = host.approve_all()
        if approved:
            approved_total.extend(approved)
            log(f"    approved: {', '.join(approved)}")
        messages = [m for m in host.history(desk) if int(m.get("id", "0")) > after_id]
        for m in messages:
            if m["id"] not in seen:
                seen.add(m["id"])
                first = m.get("text", "").strip().splitlines()[:1]
                log(f"    [{m['id']}] {m.get('author')}: {first[0] if first else ''}")
        # The close is the last `hive-report` row that is not a failed-turn
        # notice ("@theorist's turn did not finish: …"); those share the author
        # because they are host-authored, but the room continues after them.
        report = next(
            (
                m for m in reversed(messages)
                if m.get("author") == HIVE_REPORT_AUTHOR
                and not m.get("text", "").lstrip().startswith("@")
            ),
            None,
        )
        if report:
            return report, messages
        time.sleep(5)
    return None, [m for m in host.history(desk) if int(m.get("id", "0")) > after_id]


def run_problem(host: Host, desk: str, pid: str, problem: dict, timeout: float, log) -> dict:
    before = host.history(desk, limit=1)
    after_id = int(before[-1]["id"]) if before else 0
    text = (
        f"Project Euler {pid}: {problem['title']}.\n\n{problem['statement']}\n\n"
        "Decide the answer as a desk: propose a candidate only once a program has printed it, "
        "support only a number you independently checked, and object to anything that did not "
        "come out of a run."
    )
    log(f"== Problem {pid} ({problem['title']}) — expecting {problem['answer'] or 'unknown'}")
    started = time.time()
    # The chat POST holds open for the whole episode (the cycle runs it
    # synchronously), and `shell` parks for approval inside it — so the
    # operator's two jobs have to run concurrently: state the problem on a
    # thread, and pump approvals from here while it runs.
    failure: list[BaseException] = []

    def state() -> None:
        try:
            host.say(desk, text)
        except BaseException as err:  # noqa: BLE001 — surfaced below
            failure.append(err)

    poster = threading.Thread(target=state, daemon=True)
    poster.start()
    report, messages = wait_for_report(host, desk, after_id, timeout, log, poster, failure)
    elapsed = round(time.time() - started, 1)
    turns = [m for m in messages if m.get("author") not in (HIVE_REPORT_AUTHOR,) and not m.get("mine")]
    activity = analyze_transcript(turns, report.get("text") if report else None)
    outcome = {
        "problem": pid,
        "title": problem["title"],
        "expected": problem["answer"],
        "elapsed_s": elapsed,
        "turns": len(turns),
        "report": report.get("text") if report else None,
        "messages": messages,
        **activity,
    }
    answer = problem["answer"]
    if report is None:
        outcome["verdict"] = "timeout"
    else:
        rtext = report.get("text", "")
        # `EpisodeOutcome::summary()` says "settled on #topic" for a converged
        # room; the other endings say deadlocked / ran out of turns / idle.
        converged = "settled on" in rtext or "onverged" in rtext
        found = integers_in(rtext)
        # The report names the carried topic; a topic is usually the number
        # itself (`#233168`) but a room may name it otherwise, so fall back to
        # the last supporting line's integers.
        if answer and answer not in found:
            for m in reversed(turns):
                if answer in integers_in(m.get("text", "")):
                    found.append(answer)
                    break
        outcome["converged"] = converged
        if answer is None:
            outcome["verdict"] = "converged (no known answer)" if converged else "undecided"
        else:
            outcome["verdict"] = (
                "correct" if converged and answer in found else
                "wrong" if converged else
                "undecided"
            )
    log(f"   -> {outcome['verdict']} after {len(turns)} turns in {elapsed}s")
    return outcome


